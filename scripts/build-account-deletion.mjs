import { readFile, writeFile } from "node:fs/promises";

// Keep the dashboard copy in sync with the exact handler exercised by Vitest.
// No bundler or additional runtime dependency is needed for this two-file tool.
const functionDirectory = new URL(
  "../supabase/functions/delete-account/",
  import.meta.url,
);
const handler = await readFile(
  new URL("handler.ts", functionDirectory),
  "utf8",
);
const adapter = (
  await readFile(new URL("index.ts", functionDirectory), "utf8")
).replace('import { createDeleteAccountHandler } from "./handler.ts";\n', "");
await writeFile(
  new URL("dashboard.ts", functionDirectory),
  "// Generated by node scripts/build-account-deletion.mjs. Do not edit directly.\n" +
    "// Paste this entire file into Supabase's delete-account Edge Function editor.\n\n" +
    handler +
    "\n" +
    adapter,
);
